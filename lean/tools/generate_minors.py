"""Generate a proof DAG. Every transition and coefficient is checked by Lean."""
from functools import cache
from itertools import zip_longest
from pathlib import Path


def square(s, t, a, b):
    return [(a, s), (b, s), (t, a), (t, b)]


def joined(edges, a, b):
    seen = {a}
    while True:
        old = len(seen)
        for u, v in edges:
            if u in seen or v in seen:
                seen.update((u, v))
        if old == len(seen):
            return b in seen


def plus(p, q):
    return [a + b for a, b in zip_longest(p, q, fillvalue=0)]


def emit():
    blocks = [square(0, 7, 5, 6), square(7, 10, 8, 9), square(10, 13, 11, 12),
              square(13, 16, 14, 15), square(16, 1, 17, 18)]
    clique = [(b, a) for a in range(5) for b in range(a+1, 5)]
    lines = ['-- Generated by tools/generate_minors.py.', 'import CondeMerino.SquareChains', '', 'namespace CondeMerino', '',
             'set_option maxRecDepth 8192', '',
             'private def e0 : Edges := []',
             'private theorem c0 : lineCoeffs e0 = [1] := rfl', '']
    count = 0

    @cache
    def visit(edges):
        nonlocal count
        if not edges:
            return 0, [1]
        (u, v), *tail = edges
        rest = tuple(tail)
        if u == v:
            i, p = visit(rest)
            values = plus([2*c for c in p], [0]+[-c for c in p])
            result = f'timesY (lineCoeffs e{i})'
            rule = f'line_loop {u} _'
            subst = f'congrArg timesY c{i}'
        else:
            contracted = tuple((u if a == v else a, u if b == v else b) for a, b in rest)
            j, q = visit(contracted)
            if joined(rest, u, v):
                i, p = visit(rest)
                values = plus(p, q)
                result = f'plus (lineCoeffs e{i}) (lineCoeffs e{j})'
                rule = f'line_ordinary {u} {v} _ (by decide) (by decide)'
                subst = f'congrPlus c{i} c{j}'
            else:
                values = [0] + q
                result = f'0 :: lineCoeffs e{j}'
                rule = f'line_bridge {u} {v} _ (by decide)'
                subst = f'congrArg (List.cons 0) c{j}'
        count += 1
        k = count
        literal = '[' + ','.join(f'({a},{b})' for a,b in edges) + ']'
        lines.extend([f'private def e{k} : Edges := {literal}',
                      f'private theorem c{k} : lineCoeffs e{k} = {values} :=',
                      f'  calc lineCoeffs e{k} = {result} := {rule.replace(" _", f" e{k}.tail", 1)}',
                      f'       _ = _ := {subst}', ''])
        return k, values

    root, values = visit(tuple(sum(blocks, []) + clique))
    lines.extend([f'def coefficients : Coeffs := {values}', '',
                  'theorem witness_coefficients : lineCoeffs witness.edges = coefficients :=',
                  f'  c{root}', ''])
    pairs = []
    for k in range(6):
        open_blocks = [square(0 if i == 0 else 4 + 3*i, 7 + 3*i, 5 + 3*i, 6 + 3*i)
                       for i in range(k)]
        op = sum(open_blocks, []) + clique
        if k:
            tip = 4 + 3*k
            cl = [(1 if a == tip else a, 1 if b == tip else b) for a, b in op]
        else:
            cl = [(1 if a == 0 else a, 1 if b == 0 else b) for a, b in clique]
        pairs.append((visit(tuple(op))[0], visit(tuple(cl))[0]))
    lines.extend(['-- Each of the twelve graph evaluations is independently derived above.',
                  'theorem chain_coefficients (i : Fin 6) :',
                  '    lineCoeffs (openEdges i) = (squarePolys i).1 ∧',
                  '    lineCoeffs (closedEdges i) = (squarePolys i).2 :=',
                  '  match i with'])
    for k, (op, cl) in enumerate(pairs):
        lines.append(f'  | ⟨{k}, _⟩ => ⟨c{op}, c{cl}⟩')
    lines.extend(['', 'end CondeMerino', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    dest = Path(__file__).resolve().parents[1]/'CondeMerino'/'Minors.lean'
    dest.write_text(emit())
